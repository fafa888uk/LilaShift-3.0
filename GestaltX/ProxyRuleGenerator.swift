/// Surge (`.sgmodule`) and Stash (`.stoverride` / YAML) routing-rule
/// generator for coexisting China-model Siri and overseas Apple
/// Intelligence (A9). The rule content is Erosion-CN's
/// `AppGroupHubView` generator (Kianuni, GPL-3.0), reimplemented for
/// LilaShift: the China Siri voice gateway and Mandarin call
/// screening must reach Apple with a real IP (`DIRECT`, never a
/// proxy or fake IP), while Apple Intelligence region checks, PCC
/// privacy-compute relay, anonymous token issuance, Siri ChatGPT
/// extensions and visual intelligence are routed to the user's
/// overseas policy group. Generating the text is pure and safe — it
/// writes nothing. Exporting shares the file, copying puts it on the
/// clipboard, and injecting writes it into a proxy client's shared
/// AppGroup only when the user explicitly confirms it (see
/// `ProxyRuleInjector`). The policy group name is user-supplied and
/// sanitized: an empty name falls back to `PROXY`.
enum ProxyRuleFormat: String, CaseIterable, Identifiable {
    case surgeModule = "surge"
    case stashOverride = "stash"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .surgeModule: return L("Surge / Loon / Shadowrocket (.sgmodule)")
        case .stashOverride: return L("Stash override rules (.stoverride / YAML)")
        }
    }

    var fileName: String {
        switch self {
        case .surgeModule: return "LilaShift-AppleIntelligence-CN.sgmodule"
        case .stashOverride: return "LilaShift-AppleIntelligence-CN.stoverride"
        }
    }
}

enum ProxyRuleGenerator {
    static func sanitizedPolicy(_ name: String) -> String {
        let trimmed = name.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? "PROXY" : trimmed
    }

    static func content(for format: ProxyRuleFormat, policy: String) -> String {
        switch format {
        case .surgeModule: return buildSGModuleContent(policy: sanitizedPolicy(policy))
        case .stashOverride: return buildStashOverrideContent(policy: sanitizedPolicy(policy))
        }
    }

